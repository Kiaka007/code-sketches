"""Turn app/weights.npz into web/weights.js so the browser can run the model.

Why a .js file and not .json: a <script> tag loads from disk (file://) as well
as from a server, while fetch() of a .json file is blocked when the page is
opened straight from disk. The data is plain JSON assigned to one global.

Run from this folder:  python3 export_weights.py
Re-run it whenever app/weights.npz is retrained.
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
w = np.load(os.path.join(HERE, "..", "app", "weights.npz"))

out = {}
for k in w.files:
    a = w[k]
    if a.dtype.kind in "fc":
        out[k] = np.round(a, 7).tolist()   # 7 decimals: same text out, smaller file
    else:
        out[k] = [str(x) for x in a]       # vocab, source_names

with open(os.path.join(HERE, "weights.js"), "w") as f:
    f.write("// Generated by export_weights.py from app/weights.npz. Do not edit by hand.\n")
    f.write("window.ABC_WEIGHTS = ")
    json.dump(out, f, separators=(",", ":"))
    f.write(";\n")
print("wrote weights.js")
